/** Shared building blocks used by more than one view. */
import { h } from '../lib/dom.js';
import { fmt } from '../lib/format.js';
import { token } from '../charts/core.js';

export function pageHead(title, description, extra = null) {
  return h('div', { class: 'page-head' }, [
    h('h1', { text: title }),
    description ? h('p', { text: description }) : null,
    extra,
  ]);
}

export function statTile(label, value, sub = null) {
  return h('div', { class: 'stat' }, [
    h('div', { class: 'stat__label', text: label }),
    h('div', { class: 'stat__value', text: value }),
    sub ? h('div', { class: 'stat__sub', text: sub }) : null,
  ]);
}

export function card(children, className = '') {
  return h('div', { class: `card ${className}`.trim() }, children);
}

export function chip(text, variant = '') {
  return h('span', { class: `chip ${variant ? `chip--${variant}` : ''}`.trim(), text });
}

export function playerLink(player, label = null) {
  return h('a', { href: `#/player/${player.slug}`, text: label || player.name });
}

/**
 * The standing notice shown whenever the loaded dataset is the simulated demo.
 *
 * This is deliberately impossible to miss and impossible to dismiss. A cricket
 * statistics site showing invented numbers without saying so would be worse
 * than useless, so the flag travels with the data: the pipeline writes
 * `provenance.dataset` and every page reads it.
 */
export function datasetNotice(manifest) {
  if (manifest.provenance?.dataset !== 'demo') return null;
  return h('div', { class: 'notice notice--demo', role: 'note' }, [
    h('span', { class: 'notice__icon', text: '⚠', 'aria-hidden': 'true' }),
    h('div', {}, [
      h('strong', { text: 'Simulated demo data — these are not real cricketers' }),
      h('p', {}, [
        document.createTextNode(
          'Every player, team, venue and number on this site was generated by a seeded '
          + 'match simulator so the interface is explorable out of the box. To load real '
          + 'ball-by-ball data from Cricsheet, run '),
        h('code', { text: 'python -m pipeline all' }),
        document.createTextNode('. '),
        h('a', { href: '#/about', text: 'How the data is built' }),
      ]),
    ]),
  ]);
}

/** One strength or weakness, rendered with its evidence attached. */
export function findingCard(claim) {
  const isStrength = claim.kind === 'strength';
  const confidenceVariant = claim.confidence === 'high' ? 'high'
    : (claim.confidence === 'low' ? 'low' : '');
  return h('div', { class: `finding finding--${claim.kind}` }, [
    h('span', {
      class: 'finding__icon', 'aria-hidden': 'true',
      text: isStrength ? '▲' : '▼',
    }),
    h('div', { class: 'finding__title' }, [
      document.createTextNode(claim.subject),
      h('span', { class: 'sr-only', text: isStrength ? ' — strength' : ' — weakness' }),
    ]),
    h('div', { class: 'finding__body', text: claim.text }),
    h('div', { class: 'finding__meta' }, [
      chip(claim.dimension),
      chip(`${fmt.ordinal(claim.percentile)} percentile`),
      chip(`${claim.confidence} confidence`, confidenceVariant),
      chip(claim.sampleNote),
    ]),
  ]);
}

export function emptyState(title, detail) {
  return h('div', { class: 'empty' }, [
    h('h3', { text: title }),
    detail ? h('p', { class: 'small', text: detail }) : null,
  ]);
}

/** A segmented format switcher. Returns { node, value, onChange }. */
export function formatSwitcher(formats, current, onChange, manifest) {
  const box = h('div', { class: 'seg', role: 'group', 'aria-label': 'Format' });
  for (const fmtKey of formats) {
    const label = manifest?.formats?.[fmtKey]?.label || fmtKey.toUpperCase();
    const btn = h('button', {
      type: 'button', text: label,
      'aria-pressed': String(fmtKey === current),
    });
    btn.addEventListener('click', () => {
      if (fmtKey === current) return;
      onChange(fmtKey);
    });
    box.appendChild(btn);
  }
  return box;
}

/** Colour a bowling type by family, so pace and spin read apart everywhere. */
export function familyColour(family) {
  return family === 'spin' ? token('--spin') : token('--pace');
}

export function formatLabel(manifest, fmtKey) {
  return manifest?.formats?.[fmtKey]?.label || fmtKey.toUpperCase();
}

/** Sort format keys into the conventional Test / ODI / T20I order. */
const FORMAT_ORDER = ['test', 'odi', 't20i', 'ipl', 'bbl', 'psl'];
export function orderFormats(keys) {
  return [...keys].sort((a, b) => {
    const ai = FORMAT_ORDER.indexOf(a);
    const bi = FORMAT_ORDER.indexOf(b);
    return (ai === -1 ? 99 : ai) - (bi === -1 ? 99 : bi);
  });
}
